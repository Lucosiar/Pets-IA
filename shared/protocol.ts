/**
 * Contract between the agent and its overlays (macOS: Sources/PetsCore/Protocol.swift;
 * Windows: windows/PetsIA/Protocol.cs), over a WebSocket at
 * ws://127.0.0.1:PANEL_PORT/ws?token=<pairing token>.
 * The agent sends a snapshot on connect, then one message per change. The overlays show pinned
 * sessions and those working or waiting on the user.
 */

export const PANEL_PORT = 7788;

/** The coding agent behind a session. */
export const SOURCES = ["claude", "codex"] as const;
export type SessionSource = (typeof SOURCES)[number];

/** Where the session runs, which decides how a click opens it. */
export const ORIGINS = ["desktop", "vscode", "app", "terminal"] as const;
export type SessionOrigin = (typeof ORIGINS)[number];

/** Pairing file the panel loads from ./config.json; generated by the agent. */
export interface PanelConfig {
  /** Ways to reach the agent, tried in order until one connects: ws://<address>:PANEL_PORT/ws */
  agentUrls: string[];
  token: string;
}

export const SESSION_STATES = [
  "idle", // started, no prompt yet
  "working",
  "needs_permission",
  "needs_input", // a question, a plan to review, or otherwise waiting on the user
  "compacting",
  "done", // finished its turn: the user's move
  "error",
  "ended", // process gone
] as const;

export type SessionState = (typeof SESSION_STATES)[number];

export interface SessionIcon {
  /** Sprite sheet id. */
  character: string;
  /** "#rrggbb" */
  color: string;
}

export const DEFAULT_ICON: SessionIcon = { character: "default", color: "#d97757" };
/** Codex sessions start blue so the two tools are told apart at a glance. */
export const CODEX_ICON: SessionIcon = { character: "default", color: "#4f7cff" };

export function defaultIcon(source: SessionSource): SessionIcon {
  return source === "codex" ? CODEX_ICON : DEFAULT_ICON;
}

export interface PanelSession {
  id: string;
  name: string;
  cwd: string;
  state: SessionState;
  /** Short detail for the tile, e.g. "Bash: npm test". */
  activity: string | null;
  /** The Claude process is running. */
  live: boolean;
  /** Epoch ms of the last state change. */
  stateSince: number;
  pinned: boolean;
  /** Order among pinned sessions; null when not pinned. */
  position: number | null;
  icon: SessionIcon;
  source: SessionSource;
  origin: SessionOrigin;
}

/** A session the panel can pin, running or not. */
export interface LibraryEntry {
  id: string;
  name: string;
  cwd: string;
  /** Epoch ms of its last activity. */
  lastActivityAt: number;
  pinned: boolean;
  source: SessionSource;
  origin: SessionOrigin;
}

export type ServerMessage =
  | { type: "snapshot"; sessions: PanelSession[]; focusedId: string | null }
  | { type: "session"; session: PanelSession }
  | { type: "removed"; id: string }
  | { type: "focus"; id: string | null } // the session in front in the Claude desktop app; null when none
  | { type: "library"; sessions: LibraryEntry[] } // reply to a library request, most recent first
  | { type: "error"; message: string };

/** `pin` and `icon` also accept a library session that isn't running: the agent starts tracking it. */
export type ClientMessage =
  | { type: "open"; id: string }
  | { type: "pin"; id: string; pinned: boolean }
  | { type: "icon"; id: string; icon: SessionIcon } // pins the session if it isn't yet
  | { type: "library" };
